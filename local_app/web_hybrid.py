"""Autonomous LocalAiWeb product-visual production.

Real imagery is generated by the existing ComfyUI image workflow, or by an
explicitly enabled paid image API. If neither is available, do not pretend
that abstract decorations are product photographs.
No credentials or generated media are shared with LocalAiVision's saved chats.
"""
import base64
import json
import os
import re
import uuid
from pathlib import Path
from urllib.request import Request, urlopen

def select_coding_agent(provider, status, *, allow_local_fallback=False):
    """Choose an authenticated real coding agent; never silently downgrade quality.

    The old chat-only HTML generator is available solely by explicit request or
    an explicit local-only configuration.
    """
    requested = str(provider or 'auto').strip().lower()
    if requested not in ('auto', 'claude', 'codex', 'local'):
        raise ValueError('Moteur de création inconnu.')
    if requested == 'local':
        return 'local'
    agents = ('claude', 'codex') if requested == 'auto' else (requested,)
    for candidate in agents:
        if bool((status.get(candidate) or {}).get('ready')):
            return candidate
    if requested == 'auto' and allow_local_fallback:
        return 'local'
    target = 'Claude Code ou Codex' if requested == 'auto' else (
        'Claude Code' if requested == 'claude' else 'Codex')
    raise RuntimeError(
        'Aucun agent professionnel connecté. Pour éviter de générer une ancienne '
        'maquette HTML, connecte ' + target +
        ' sur ce PC, puis réessaie. Installation : Claude Code (claude auth login) '
        'ou Codex (codex login). Ton projet reste intact.'
    )


MAX_AUTOMATIC_IMAGES = 3
PAID_OPT_IN = "LOCALAIWEB_ALLOW_PAID_IMAGES"
CLOUD_MODEL = "gpt-image-1"


def semantic_subject(request):
    text = str(request or "").lower()
    domains = (
        (r'p[eê]ch|poisson|app[aâ]t|canne|leurre', ('premium fishing accessories', 'precision fishing reel', 'handcrafted fishing lure')),
        (r'parfum|fragrance', ('luxury perfume campaign', 'minimalist perfume bottle', 'glass perfume atomizer')),
        (r'montre|horlog', ('luxury watch campaign', 'precision stainless steel watch', 'premium watch dial')),
        (r'chaussure|sneaker', ('premium footwear editorial', 'technical running shoe', 'minimalist sneaker')),
        (r'cosm[eé]t|soin|beaut[eé]', ('premium skincare campaign', 'glass skincare serum bottle', 'artisan face cream container')),
        (r'barb|coiffure|salon', ('modern premium barber studio', 'professional hair grooming tools', 'luxury barber equipment')),
        (r'voiture|automobil', ('luxury automotive editorial', 'concept electric sports car', 'precision automotive design details')),
        (r'mobilier|meuble|fauteuil', ('high-end furniture interior', 'contemporary designer chair', 'luxury interior accessory')),
        (r'bijou|joaill|collier', ('fine jewellery editorial', 'designer gold ring', 'premium necklace detail')),
    )
    for pattern, subjects in domains:
        if re.search(pattern, text, re.I):
            return subjects
    # Only choose a neutral editorial visual when the actual product is unknown.
    return ('professional brand editorial', 'minimal abstract material study', 'art-directed design still life')


def visual_plan(request, *, existing=()):
    """Bounded first-pass visual plan; never infer actual SKUs, claims or prices."""
    from local_app import web_briefing
    info = web_briefing.infer(request)
    if existing:
        # An edit must not overwrite or spend resources recreating approved photos.
        return []
    if len(str(request).strip()) < 25:
        return []
    subjects = semantic_subject(request)
    shop = info["shop"]
    importance = "premium" if info["spectacular"] else "professional"
    roles = ("hero", "product-one", "product-two") if shop else ("hero",)
    brief = str(request)[:1100]
    plans = []
    for index, role in enumerate(roles[:MAX_AUTOMATIC_IMAGES]):
        subject = subjects[min(index, len(subjects) - 1)]
        composition = ("wide horizontal hero art direction, room for overlaid headline, artistic environmental scene"
                       if role == "hero" else
                       "clean premium e-commerce product photography, centered main object, seamless studio background")
        plans.append({
            "role": role,
            "subject": subject,
            "prompt": (
                f"{importance} commercial product photography, {subject}. {composition}. "
                "Photographically plausible camera optics, accurate physically based materials, "
                "natural controlled studio lighting, intentional highlights, detailed textures, "
                "well-balanced composition, contemporary brand art direction, realistic natural shadows, "
                "no text, no logo, no watermark, no price, no UI, no misleading certification. "
                "Use the following client visual direction as a color/mood reference only: " + brief
            )[:2400],
        })
    return plans


def _cloud_image(prompt):
    """Opt-in paid API: no user key is ever sent to the browser or stored in the site."""
    if os.getenv(PAID_OPT_IN, "").strip().lower() not in ("1", "true", "yes"):
        return None
    token = os.getenv("OPENAI_API_KEY", "").strip()
    if not token:
        return None
    payload = json.dumps({
        "model": CLOUD_MODEL,
        "size": "1536x1024",
        "quality": "medium",
        "n": 1,
        "output_format": "png",
        "prompt": prompt,
    }).encode("utf-8")
    request = Request(
        "https://api.openai.com/v1/images/generations",
        data=payload,
        headers={"Content-Type": "application/json",
                 "Authorization": "Bearer " + token},
        method="POST",
    )
    with urlopen(request, timeout=180) as response:
        result = json.loads(response.read(30 * 1024 * 1024))
    encoded = (result.get("data") or [{}])[0].get("b64_json")
    if not encoded:
        raise RuntimeError("Le service d'images n'a renvoyé aucune photo.")
    raw = base64.b64decode(encoded, validate=True)
    if not raw.startswith(b"\x89PNG\r\n\x1a\n") or len(raw) > 24 * 1024 * 1024:
        raise RuntimeError("Image de sortie invalide.")
    return raw


def make_visuals(store, project_id, request, local_generate=None, *, local_ready=False):
    """Generate genuine photos when available; return transparent diagnostics otherwise.

    local_generate(project_id, prompt) is the already installed ComfyUI path.
    No image service is installed or charged automatically by this function.
    """
    existing = [a for a in store.assets(project_id) if a["path"].lower().endswith((".png", ".jpg", ".jpeg", ".webp", ".avif"))]
    plan = visual_plan(request, existing=existing)
    if not plan:
        return {"assets": existing, "generated": [], "notes": [], "ready": bool(existing)}
    generated, notes = [], []
    site = store.project_dir(project_id) / "site"
    paid_ready = os.getenv(PAID_OPT_IN, '').strip().lower() in ('1','true','yes') and bool(os.getenv('OPENAI_API_KEY'))
    if not local_ready and not paid_ready:
        notes.append("Moteur d'images non prêt : aucune photo artificielle n'a été inventée. "
                     "Installe le modèle d'images LocalAiVision/ComfyUI, ou active volontairement "
                     "une API d'images pour générer les visuels automatiquement.")
        return {"assets": [], "generated": [], "notes": notes, "ready": False}
    for index, item in enumerate(plan):
        try:
            if local_ready and local_generate is not None:
                result = local_generate(project_id, item["prompt"])
                image_path = result["path"]
                provider = "comfyui"
            else:
                raw = _cloud_image(item["prompt"])
                if raw is None:
                    raise RuntimeError("Le moteur d'images n'est pas connecté.")
                filename = f"auto-{item['role']}-{uuid.uuid4().hex[:7]}.png"
                dest = (site / "assets" / filename).resolve()
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(raw)
                image_path = "assets/" + filename
                provider = "paid-image-api"
            if not (site / image_path).resolve().is_file():
                raise RuntimeError("La photo générée n'existe pas dans le dossier du projet.")
            generated.append({"role": item["role"], "path": image_path,
                              "subject": item["subject"], "provider": provider,
                              "status": "illustrative_generated_image"})
        except Exception as exc:
            notes.append(f"{item['role']} : photo non générée ({str(exc)[:200]}).")
            # Do not repeatedly time out if the image engine is failing.
            break
    if generated:
        meta = store.meta(project_id)
        meta["auto_visuals"] = generated
        store.write_meta(project_id, meta)
    return {"assets": store.assets(project_id), "generated": generated,
            "notes": notes, "ready": bool(generated)}


def developer_brief(request, visuals):
    lines = [
        "You are building a real product, not an HTML mockup. User request takes priority:",
        request,
        "",
        "SITE VISUALS (already available as local project assets):",
    ]
    for visual in visuals.get("generated", []):
        lines.append(f"- {visual['role']}: {visual['path']} ({visual['subject']}). "
                     "Include this real generated image visibly and responsively.")
    if not visuals.get("generated"):
        lines.append("- No generated photos available. Never use fake product imagery or claim actual photos exist. "
                     "Use premium CSS/SVG decoration while keeping genuine-image requests visible as unmet.")
    lines.extend([
        "",
        "ART DIRECTION: Strong hierarchy, large carefully composed hero, consistent brand palette, "
        "responsive high-quality layout, meaningful spacing, generous product photography, polished hover states.",
        "FOR STORE: functional search and category filtering, sensible navigation, product grids and detail affordances. "
        "Do not invent actual inventory records or prices as verified; clearly mark sample catalog if used.",
        "3D: If explicitly requested, implement real Three.js/GLB/PBR and scroll choreography. "
        "Do not force 3D into simple sites. Never claim photo-to-3D without a geometry pipeline.",
        "PRODUCTION: If using React, prefer Vite SPA build with dist/index.html; the local preview must be fully functional. Build/run/check the site, respect reduced motion and accessibility, never fake payment/auth.",
        "Do not copy proprietary templates; create an original high-quality visual identity.",
    ])
    return "\n".join(lines)


def asset_manifest(visuals):
    """Structured asset manifest, so agents use real image paths."""
    return json.dumps({
        'generated_images': visuals.get('generated', []),
        'notes': visuals.get('notes', []),
        'example_products_are_not_verified_inventory': True,
    }, ensure_ascii=False)


def contract_repair_prompt(original_request, findings):
    return (
        "FIX THE CURRENT WEBSITE IN PLACE. Do not discard any approved features. "
        "The project was checked against the user specification and failed these tests:\n"
        + "\n".join("- " + f["fix"] for f in findings[:12])
        + "\nKeep the requested palette, brand name, pages, search and categories. "
        "Use available local images; never claim example products represent real inventory. "
        "Preserve features already working.\nUSER REQUEST:\n" + original_request
    )


def code_quality_report(store, project_id, request, integrations):
    """Check real build output; never rate visual beauty without inspecting a screenshot."""
    from local_app import web_briefing
    site = store.project_dir(project_id) / 'site'
    files = store.text_files(project_id)
    syntax = integrations.validate_site(site)
    if (site / 'package.json').is_file():
        try:
            build = integrations.build_project(site)
        except Exception as exc:
            build = {'ok': False, 'message': str(exc)[:1500]}
        source = '\n'.join(files.values())
        norm = web_briefing.plain(source)
        info = web_briefing.infer(request)
        findings = []
        def add(id, fix): findings.append({'id': id, 'fix': fix})
        if not build.get('ok'):
            add('framework_build', 'Install dependencies and fix the production build: ' + build['message'])
        if build.get('ok') and not build.get('output_dir'):
            add('preview_missing', 'Provide a static build output (Vite dist/) so the full website can be previewed.')
        if len(source) < 3500:
            add('framework_depth', 'Implement the complete site, not a skeletal React shell.')
        brand = __import__('re').search(r"(?:s['’]appelle|nomm[eé]|appelle)\s+([\w-]{3,})", request, __import__('re').I)
        if brand and web_briefing.plain(brand.group(1)) not in norm:
            add('brand', 'Display the requested brand name in rendered app components.')
        if info['shop'] and not any(x in norm for x in ('catalogue', 'produit', 'product', 'shop')):
            add('products', 'Provide complete store products and categories.')
        if info['shop'] and web_briefing.has(r'\brecherche|search\b', request) and not any(x in norm for x in ('recherch', 'search', 'filter')):
            add('search', 'Implement functional product search and category filtering.')
        if 'bleu' in info['colors'] and not any(x in norm for x in ('blue', 'cyan', 'bleu', '#0ea5', '#38bd', '#0284', '#2563')):
            add('blue_palette', 'Use the explicitly requested blue palette.')
        if 'vert' in info['colors'] and not any(x in norm for x in ('green', 'lime', 'vert', '#4ade', '#22c5', '#a3e6')):
            add('green_palette', 'Use the explicitly requested green palette.')
        structural = {'ok': not findings and bool(build.get('ok')),
                      'score': None, 'blockers': findings, 'checks': [],
                      'note': 'Framework compiled and source contract checked, visual QA not scored.'}
    else:
        build = {'ok': True, 'kind': 'static'}
        findings = web_briefing.audit(files, request)
        structural = store.preflight(project_id)
    return {'ok': not findings and syntax['ok'] and structural['ok'],
            'findings': findings, 'syntax': syntax,
            'preflight': structural, 'build': build}


def build_with_agent(store, project_id, user_prompt, agent, integrations, visuals):
    """Claude/Emergent-style agent workflow: implement, build, inspect, repair.

    Inspections use actual browser screenshots when Playwright is available.
    An unavailable visual inspector is reported honestly, never passed.
    The source of truth remains the project's real files.
    """
    import time
    from local_app import web_browser_qa

    site = store.project_dir(project_id) / 'site'
    ignore = site / '.gitignore'
    if not ignore.is_file():
        ignore.write_text('.localaiweb-qa/\n', encoding='utf-8')
    elif '.localaiweb-qa' not in ignore.read_text(encoding='utf-8'):
        with ignore.open('a', encoding='utf-8') as stream:
            stream.write('\n.localaiweb-qa/\n')

    instruction = developer_brief(user_prompt, visuals)
    instruction += '\n' + asset_manifest(visuals)
    instruction += (
        '\nAGENT PROCESS: Plan the visual structure and design system first. '
        'Build real pages and their actual interactions. Install required dependencies, '
        'run the production build, and fix all runtime errors. User brief is authoritative. '
        'A premium website is not a short HTML forum or a generic template. '
        'Use original art direction and real product assets. Prefer React/Vite for '
        'interactive sites and React Three Fiber for demanding real 3D work. '
        'A simple brochure site may remain semantic HTML/CSS if that is more appropriate.'
    )
    store.append_chat(project_id, 'user', user_prompt)
    store.snapshot(project_id, 'Avant : génération hybride')
    result = agent(site, instruction)
    report = code_quality_report(store, project_id, user_prompt, integrations)
    repair_count = 0

    if not report['ok']:
        findings = list(report['findings'])
        findings.extend({'fix': row['message']} for row in report['syntax'].get('issues', []))
        findings.extend({'fix': row.get('label', 'Qualité insuffisante')}
                        for row in report['preflight'].get('blockers', []))
        agent(site, contract_repair_prompt(user_prompt, findings))
        repair_count += 1
        report = code_quality_report(store, project_id, user_prompt, integrations)

    visual = {'status': 'not_run', 'issues': [], 'reviewed': False,
              'screenshots': []}
    if report['ok']:
        visual = web_browser_qa.review(site, build=report.get('build'))
        if visual.get('reviewed') and visual.get('screenshots'):
            # Run the agent in a vision-capable review role, looking at actual
            # desktop, tablet and mobile screenshots, not guessed CSS properties.
            agent(site, web_browser_qa.creative_review_prompt(user_prompt, visual))
            repair_count += 1
            report = code_quality_report(store, project_id, user_prompt, integrations)
            if report['ok']:
                visual = web_browser_qa.review(site, build=report.get('build'))
            else:
                visual = {'status': 'failed', 'reviewed': False,
                          'issues': ['Le site a échoué aux contrôles après revue visuelle.'],
                          'screenshots': []}

    meta = store.meta(project_id)
    meta['updated_at'] = time.time()
    meta['last_summary'] = str(result.get('summary') or 'Site créé par un agent de développement')[-400:]
    meta['last_quality_score'] = report['preflight'].get('score')
    meta['last_agent_quality'] = {
        'ok': report['ok'], 'visual': visual.get('status'),
        'issues': [f['id'] for f in report['findings']],
        'repairs': repair_count,
    }
    store.write_meta(project_id, meta)
    feedback = meta['last_summary']
    if not report['ok']:
        feedback += '\nLe site reste incomplet : ' + ', '.join(
            row['id'] for row in report['findings'][:6])
    elif visual['status'] == 'unavailable':
        feedback += '\nAperçu construit, mais la vérification visuelle automatique nécessite Playwright et Chromium.'
    elif visual['status'] == 'failed':
        feedback += '\nÀ corriger dans le rendu navigateur : ' + '; '.join(visual['issues'][:3])
    elif visual['status'] == 'passed':
        feedback += '\nVérification navigateur : ordinateur, tablette et téléphone contrôlés.'
    store.append_chat(project_id, 'assistant', feedback)
    payload = store.payload(project_id)
    payload['summary'] = feedback
    payload['quality'] = report['preflight']
    payload['hybrid_validation'] = {**report, 'visual': visual,
                                    'repairs': repair_count}
    payload['visuals'] = visuals
    return payload
